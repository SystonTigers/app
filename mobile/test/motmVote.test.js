/* Man of the Match vote length. Usage: node test/motmVote.test.js */
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const ts = require('typescript');
const js = ts.transpileModule(fs.readFileSync(path.join(__dirname, '../src/utils/motmVote.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const mod = { exports: {} };
new Function('module', 'exports', 'require', js)(mod, mod.exports, require);
const { customHours, lengthText, closesInText, votePrompt } = mod.exports;
assert.strictEqual(customHours('6', 'hours'), 6);
assert.strictEqual(customHours('2', 'days'), 48);
assert.strictEqual(customHours('3', 'days'), 72);
assert.strictEqual(customHours('4', 'days'), null);
assert.strictEqual(customHours('73', 'hours'), null);
assert.strictEqual(customHours('0.5', 'hours'), null);
assert.strictEqual(customHours('1,5', 'hours'), 1.5);
assert.strictEqual(customHours('', 'hours'), null);
assert.strictEqual(customHours('abc', 'days'), null);
assert.strictEqual(lengthText(3), '3 hours');
assert.strictEqual(lengthText(24), '1 day');
assert.strictEqual(lengthText(72), '3 days');
const now = Date.parse('2026-10-26T15:00:00Z');
const at = (mins) => new Date(now + mins * 60000).toISOString();
assert.strictEqual(closesInText(at(25), now), 'Closes in 25 minutes');
assert.strictEqual(closesInText(at(120), now), 'Closes in 2 hours');
assert.strictEqual(closesInText(at(60 * 72), now), 'Closes in 3 days');
assert.strictEqual(closesInText(at(-1), now), null);
assert.strictEqual(closesInText(null, now), null);
const vote = (matchId, extra) => ({ matchId, votingOpen: true, closesAt: at(180), userVote: null, match: { opponent: 'Rovers' }, ...extra });
assert.deepStrictEqual(votePrompt([vote('m1')], now), { matchId: 'm1', line: 'Who was best v Rovers? Closes in 3 hours.' });
assert.deepStrictEqual(votePrompt([vote('m1', { userVote: 'p1' }), vote('m2', { match: null, closesAt: null })], now), { matchId: 'm2', line: 'Who was best?' });
assert.strictEqual(votePrompt([vote('m1', { votingOpen: false })], now), null);
assert.strictEqual(votePrompt([vote('m1', { closesAt: at(-5) })], now), null);
assert.strictEqual(votePrompt([], now), null);
console.log('motmVote tests passed');
